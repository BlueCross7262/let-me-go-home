#!/usr/bin/env node

/**
 * Generates scripts/lib/namespace.mjs from the compiled namespace constants.
 *
 * The standalone hook scripts must keep working when dist/ is absent, so they
 * cannot import the TypeScript module directly. This script copies the values
 * out of it instead. It must never spell a namespace literal itself — values
 * are serialized from the import, and functions are re-emitted from their own
 * source text, so the TypeScript module stays the only declaration.
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as namespace from '../dist/constants/namespace.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'scripts', 'lib', 'namespace.mjs');

const entries = Object.entries(namespace);
const values = entries.filter(([, value]) => typeof value !== 'function');
const functions = entries.filter(([, value]) => typeof value === 'function');

if (values.length === 0) {
  throw new Error('dist/constants/namespace.js exported no values — was tsc run first?');
}

const lines = [
  '// Generated by scripts/build-namespace.mjs from src/constants/namespace.ts.',
  '// Do not edit this file directly.',
  '',
];

for (const [name, value] of values) {
  if (typeof value !== 'string') {
    throw new Error(`namespace constant ${name} is not a string — the generator cannot serialize it`);
  }
  lines.push(`export const ${name} = ${JSON.stringify(value)};`);
}

for (const [name, value] of functions) {
  const source = value.toString();
  if (!source.startsWith(`function ${name}(`)) {
    throw new Error(`namespace export ${name} is not a plain named function declaration`);
  }
  lines.push('', `export ${source}`);
}

writeFileSync(target, `${lines.join('\n')}\n`, 'utf8');
console.log(`Wrote ${target} (${values.length} constants, ${functions.length} functions)`);
